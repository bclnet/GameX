    fn putI32(b: &mut [u8], at: usize, v: i32) { b[at..at + 4].copy_from_slice(&v.to_le_bytes()); }
    fn putF32(b: &mut [u8], at: usize, v: f32) { b[at..at + 4].copy_from_slice(&v.to_le_bytes()); }

    /// 408-byte `M_Header`. Name sits at offset 12. The six vectors start at 80. Flags are at 152.
    fn mdl40(magic: i32, version: i32, name: &[u8], flags: i32) -> Vec<u8> {
        let mut b = vec![0u8; 408];
        putI32(&mut b, 0, magic);
        putI32(&mut b, 4, version);
        let n = name.len().min(64);
        b[12..12 + n].copy_from_slice(&name[..n]);
        putF32(&mut b, 80, 1.0);
        putF32(&mut b, 84, 2.0);
        putF32(&mut b, 88, 3.0);
        putF32(&mut b, 92, 4.0);
        putF32(&mut b, 96, 5.0);
        putF32(&mut b, 100, 6.0);
        putF32(&mut b, 104, -1.0);
        putF32(&mut b, 108, -2.0);
        putF32(&mut b, 112, -3.0);
        putF32(&mut b, 116, 7.0);
        putF32(&mut b, 120, 8.0);
        putF32(&mut b, 124, 9.0);
        putF32(&mut b, 128, 0.5);
        putF32(&mut b, 132, 0.25);
        putF32(&mut b, 136, 0.125);
        putF32(&mut b, 140, 10.0);
        putF32(&mut b, 144, 11.0);
        putF32(&mut b, 148, 12.0);
        putI32(&mut b, 152, flags);
        b
    }

    #[test]
    fn mdl40ReadsTheHeaderAndRejectsABadFile() {
        use std::io::ErrorKind;
        assert_eq!(HeaderFlags::AMBIENT_BOOST, HeaderFlags::DO_NOT_CAST_SHADOWS);
        assert_eq!(HeaderFlags::AMBIENT_BOOST, HeaderFlags::CAST_TEXTURE_SHADOWS);
        let empty = <dyn Archive>::empty();
        let file = Arc::new(FileSource { path: "models/scout.mdl".into(), ..Default::default() });
        let good = mdl40(0x54534449u32 as i32, 40, b"ab\0cd\xff", HeaderFlags::STATIC_PROP.0);
        let mut stream: Stream = Box::new(Cursor::new(good.clone()));
        let err = getResult(Binary_Mdl40::factory(&mut stream, file.clone(), &*empty)).unwrap_err();
        assert!(err.to_string().contains("InvalidCastException: BinaryArchive"), "{err}");

        let arc = archive("a.mdl", Some("07x"));
        let mut stream: Stream = Box::new(Cursor::new(vec![0u8; 16]));
        let err = getResult(Binary_Mdl40::factory(&mut stream, file.clone(), &arc)).unwrap_err();
        assert_eq!(err.kind(), ErrorKind::UnexpectedEof);

        let mut stream: Stream = Box::new(Cursor::new(mdl40(0, 40, b"a", 0)));
        let err = getResult(Binary_Mdl40::factory(&mut stream, file.clone(), &arc)).unwrap_err();
        assert!(err.to_string().contains("BAD MAGIC"), "{err}");
        let mut stream: Stream = Box::new(Cursor::new(mdl40(0x54534449u32 as i32, 39, b"a", 0)));
        let err = getResult(Binary_Mdl40::factory(&mut stream, file.clone(), &arc)).unwrap_err();
        assert!(err.to_string().contains("BAD VERSION"), "{err}");
        let mut stream: Stream = Box::new(Cursor::new(mdl40(0x54534449u32 as i32, 40, b"", 0)));
        let err = getResult(Binary_Mdl40::factory(&mut stream, file.clone(), &arc)).unwrap_err();
        assert!(err.to_string().contains("The file '' is not a model main header file"), "{err}");

        let mut stream: Stream = Box::new(Cursor::new(good));
        let tag = getResult(Binary_Mdl40::factory(&mut stream, file.clone(), &arc)).unwrap();
        let Tag::Info(info) = tag else { panic!("info"); };
        let nodes = info.getInfoNodes(None, Some(&file), &Tag::None);
        let Tag::MetaContent(content) = &nodes[0].tag else { panic!("content"); };
        assert_eq!(content.name, "scout.mdl");
        assert_eq!(content.type_, "Text");
        let mdl = content.value.asAny().unwrap().downcast_ref::<Binary_Mdl40>().expect("mdl");
        assert_eq!(mdl.name, "ab\0cd?");
        assert_eq!(mdl.eyePosition, glam::Vec3::new(1.0, 2.0, 3.0));
        assert_eq!(mdl.illumPosition, glam::Vec3::new(4.0, 5.0, 6.0));
        assert_eq!(mdl.boundingMin, glam::Vec3::new(-1.0, -2.0, -3.0));
        assert_eq!(mdl.boundingMax, glam::Vec3::new(7.0, 8.0, 9.0));
        assert_eq!(mdl.clippingMin, glam::Vec3::new(0.5, 0.25, 0.125));
        assert_eq!(mdl.clippingMax, glam::Vec3::new(10.0, 11.0, 12.0));
        assert_eq!(mdl.flags, HeaderFlags::STATIC_PROP);
        assert_eq!(nodes[1].name.as_deref(), Some("UnknownFileModel"));
        assert_eq!(nodes[1].items[0].name.as_deref(), Some("Name: ab\0cd?"));
    }
