impl Binary_Mdl40 {
    const M_MAGIC: u32 = 0x54534449; // IDST

    pub fn factory<'a>(r: &'a mut Stream, f: Arc<FileSource>, s: &'a dyn Archive) -> Task<'a, Tag> {
        fromResult(Self::new(r, &f, s).map(|m| Tag::Info(m)))
    }

    pub fn new(r: &mut Stream, f: &FileSource, s: &dyn Archive) -> io::Result<Arc<Self>> {
        let _bin = s.asBinaryArchive().ok_or_else(|| Error::new(ErrorKind::InvalidData, "InvalidCastException: BinaryArchive"))?;
        let header = r.readS::<M_Header>()?;
        if header.Magic as u32 != Self::M_MAGIC { return Err(Error::new(ErrorKind::InvalidData, "BAD MAGIC")); }
        else if header.Version < 40 { return Err(Error::new(ErrorKind::InvalidData, "BAD VERSION")); }
        let name = fixedAString(&header.Name);
        if name.is_empty() { return Err(Error::new(ErrorKind::InvalidData, format!("The file '{name}' is not a model main header file"))); }
        let path = f.path.as_str();
        let pathExt = extension(path);
        let _pathName = &path[..path.len() - pathExt.len()];
        Ok(Arc::new_cyclic(|w| Self {
            name,
            eyePosition: header.EyePosition,
            illumPosition: header.IllumPosition,
            boundingMin: header.Min,
            boundingMax: header.Max,
            clippingMin: header.BBMin,
            clippingMax: header.BBMax,
            flags: HeaderFlags(header.Flags),
            me: w.clone(),
        }))
    }
}

