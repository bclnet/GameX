        let (mut bytes, _) = vpk(1, 0x7FFF, b"hi", false);
        // CRC sits after the three names. Flip the first crc byte by rewriting the entry hash to 0.
        // Easier: read, then patch hash via a second built file.
        let _ = &mut bytes;
        let (mut bytes, _) = vpk(1, 0x7FFF, b"hi", false);
        // names: 01 01 00, 20 01 00, 02 01 00, then crc u32. Find crc by rebuilding without payload match: set crc bytes to 0.
        let crcAt = 12 + vw("\u{0101}").len() + vw("\u{0120}").len() + vw("\u{0102}").len();
        bytes[crcAt..crcAt + 4].fill(0);
