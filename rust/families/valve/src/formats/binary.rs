struct Verification {
    archiveMd5sP: u64,
    treeChecksum: Option<Vec<u8>>,
    archiveMd5EntriesChecksum: Option<Vec<u8>>,
    wholeFileChecksumP: u64,
    wholeFileChecksum: Option<Vec<u8>>,
    publicKey: Option<Vec<u8>>,
    signature: Option<Vec<u8>>,
}

impl Verification {
    fn read(r: &mut dyn VfsRead, h: &V_HeaderV2) -> io::Result<Self> {
        let mut v = Verification {
            archiveMd5sP: 0,
            treeChecksum: None,
            archiveMd5EntriesChecksum: None,
            wholeFileChecksumP: 0,
            wholeFileChecksum: None,
            publicKey: None,
            signature: None,
        };
        if h.ArchiveMd5SectionSize != 0 {
            v.archiveMd5sP = r.tell()?;
            let count = h.ArchiveMd5SectionSize as usize / size_of::<V_ArchiveMd5>();
            let _entries = r.readSArray::<V_ArchiveMd5>(count, size_of::<V_ArchiveMd5>() as i32)?;
        }
        if h.OtherMd5SectionSize != 0 {
            v.treeChecksum = Some(r.readBytes(16)?);
            v.archiveMd5EntriesChecksum = Some(r.readBytes(16)?);
            v.wholeFileChecksumP = r.tell()?;
            v.wholeFileChecksum = Some(r.readBytes(16)?);
        }
        if h.SignatureSectionSize != 0 {
            let _position = r.tell()?;
            let publicKeySize = r.readInt32()?;
            if h.SignatureSectionSize == 20 && publicKeySize == MAGIC_I32 { return Ok(v); }
            if publicKeySize < 0 { return Err(Error::new(ErrorKind::InvalidInput, "ArgumentOutOfRangeException: publicKeySize")); }
            v.publicKey = Some(r.readBytes(publicKeySize as usize)?);
            let sigLen = r.readInt32()?;
            if sigLen < 0 { return Err(Error::new(ErrorKind::InvalidInput, "ArgumentOutOfRangeException: signature")); }
            v.signature = Some(r.readBytes(sigLen as usize)?);
        }
        Ok(v)
    }

    fn verifyHashes(&self, r: &mut dyn VfsRead, treeSize: u32, h: &V_HeaderV2, headerPosition: u32) -> io::Result<()> {
        r.seek(SeekFrom::Start(headerPosition as u64))?;
        let hash = md5Of(&r.readBytes(treeSize as usize)?);
        let tree = self.treeChecksum.as_deref().ok_or_else(|| Error::new(ErrorKind::InvalidData, "NullReferenceException: TreeChecksum"))?;
        if hash != tree { return Err(Error::new(ErrorKind::InvalidData, format!("File tree checksum mismatch ({} != expected {})", hex(&hash), hex(tree)))); }
        r.seek(SeekFrom::Start(self.archiveMd5sP))?;
        let hash = md5Of(&r.readBytes(h.ArchiveMd5SectionSize as usize)?);
        let entries = self.archiveMd5EntriesChecksum.as_deref().ok_or_else(|| Error::new(ErrorKind::InvalidData, "NullReferenceException: ArchiveMd5EntriesChecksum"))?;
        if hash != entries { return Err(Error::new(ErrorKind::InvalidData, format!("Query MD5 checksum mismatch ({} != expected {})", hex(&hash), hex(entries)))); }
        r.seek(SeekFrom::Start(0))?;
        let hash = md5Of(&r.readBytes(self.wholeFileChecksumP as usize)?);
        let whole = self.wholeFileChecksum.as_deref().ok_or_else(|| Error::new(ErrorKind::InvalidData, "NullReferenceException: WholeFileChecksum"))?;
        if hash != whole { return Err(Error::new(ErrorKind::InvalidData, format!("Package checksum mismatch ({} != expected {})", hex(&hash), hex(whole)))); }
        Ok(())
    }

    fn verifySignature(&self) -> io::Result<()> {
        if self.publicKey.is_none() || self.signature.is_none() { return Ok(()); }
        Err(Error::new(ErrorKind::Unsupported, "NotImplementedException: RSA.VerifyData"))
    }
}

fn md5Of(bytes: &[u8]) -> Vec<u8> { Md5::digest(bytes).to_vec() }
fn hex(bytes: &[u8]) -> String { bytes.iter().map(|b| format!("{b:02x}")).collect() }

/// C# `Path.GetExtension` / `GetFileNameWithoutExtension` mask. `Remove(1, 1)` drops one character.
pub fn vpkFileMask(path: &str) -> String {
    let mut extension = extension(path);
    if extension.ends_with("_c") { extension.truncate(extension.len() - 2); }
    if extension.starts_with(".v") { extension.remove(1); }
    let name = fileName(path);
    let stem = name.rfind('.').map(|i| &name[..i]).unwrap_or(&name);
    format!("{stem}{extension}")
}

