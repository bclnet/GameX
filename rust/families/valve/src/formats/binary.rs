// PORT-SOURCE: Families/GameX.Valve/Formats/Binary.cs
// PORT-SHA: 5db52ffb714470c8
// PORT-STATUS: partial
//
// Ported: `Binary_Vpk` `Read` / `ReadData` (the Source archive Arkane opens).
// `ReadVWString` is UTF-16LE stopped on the first 0 byte, so an ASCII Source
// tree does not come out as ASCII. Same as C#. Version 2 runs the MD5 checks
// unless `Engine.v` contains `x`. An empty checksum section is
// `NullReferenceException`, because C# calls `SequenceEqual` on a null array.
// `VerifySignature` reads the key and then fails: RSA PKCS1 SHA-256 is not in
// the Rust tree (`NotImplementedException: RSA.VerifyData`). A CS2 section
// (`SignatureSectionSize == 20` and the next int equal to the magic) returns
// before that, as in C#.
//
// Ported with the archive: `Binary_Mdl40` (Source `.mdl`). The constructor
// reads `M_Header` and stores the name, six vectors and flags. The bone,
// sequence and texture loads stay commented out, as in C#. `FixedAString`
// trims trailing NULs and turns a byte above 127 into `?`. The factory casts
// to `BinaryArchive` before it reads. `Binary_Mdl10` has its own `M_Header`;
// that reader is still a slot, so these struct names are Mdl40's.
//
// Factory slots only: `Binary_Mdl10`, `Binary_Src`, `Binary_Wad3X`. The rest
// of this file is not ported. PORT_MAP stays `todo`.
//
// Python's `Binary_Mdl40` already reads the header. Its info group is `Model`
// (C# is `UnknownFileModel`) and the value is the string `self`. A byte above
// 127 becomes U+FFFD. `M_Header2`'s size is 244 and `M_Texture`'s is 80.

