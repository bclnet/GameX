/// C# `UnsafeX.FixedAString`: the whole field, `?` above 0x7F, trailing NULs trimmed.
fn fixedAString(data: &[u8]) -> String {
    let end = data.iter().rposition(|&c| c != 0).map(|i| i + 1).unwrap_or(0);
    data[..end].iter().map(|&c| if c < 0x80 { c as char } else { '?' }).collect()
}

