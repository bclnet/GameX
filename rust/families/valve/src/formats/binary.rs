impl ArcBinary for Binary_Vpk {
    fn read<'a>(&'a self, source: &'a BinaryArchive, r: Option<&'a mut dyn VfsRead>, _tag: &'a Tag) -> Task<'a, ()> {
        Box::pin(async move {
            let r = r.ok_or_else(|| Error::new(ErrorKind::InvalidInput, "r"))?;
            let extended = source.base.game.engine.1.as_deref().is_some_and(|v| v.contains('x'));
            source.setFiles(Some(Vec::new()));
            *source.fileMask.lock().unwrap() = Some(vpkFileMask);

            let mut files = Vec::new();
            let parsed = (|| -> io::Result<(u32, u32, u32, V_HeaderV2)> {
                let mut blobPath = source.base.binPath.clone();
                let dirVpk = blobPath.len() >= 8 && blobPath[blobPath.len() - 8..].eq_ignore_ascii_case("_dir.vpk");
                if dirVpk { blobPath.truncate(blobPath.len() - 8); }
                if r.readUInt32()? != MAGIC { return Err(Error::new(ErrorKind::InvalidData, "BAD MAGIC")); }
                let version = r.readUInt32()?;
                let treeSize = r.readUInt32()?;
                if version == 0x00030002 { return Err(Error::new(ErrorKind::InvalidData, "Unsupported VPK: Apex Legends, Titanfall")); }
                else if version > 2 { return Err(Error::new(ErrorKind::InvalidData, format!("Bad VPK version. ({version})"))); }
                let headerV2 = if version == 2 { r.readS::<V_HeaderV2>()? } else { V_HeaderV2::default() };
                let headerPosition = r.tell()? as u32;
                loop {
                    let typeName = r.readVWString(usize::MAX, 0, None)?;
                    if typeName.is_empty() { break; }
                    loop {
                        let directoryName = r.readVWString(usize::MAX, 0, None)?;
                        if directoryName.is_empty() { break; }
                        loop {
                            let fileName = r.readVWString(usize::MAX, 0, None)?;
                            if fileName.is_empty() { break; }
                            let dir = if directoryName.starts_with(' ') { String::new() } else { format!("{directoryName}/") };
                            let hash = r.readUInt32()? as u64;
                            let preloadLen = r.readUInt16()? as usize;
                            let id = r.readUInt16()? as i32;
                            let offset = r.readUInt32()? as i64;
                            let fileSize = r.readUInt32()? as i64;
                            let terminator = r.readUInt16()?;
                            if terminator != 0xFFFF { return Err(Error::new(ErrorKind::InvalidData, format!("Invalid terminator, was 0x{terminator:X} but expected 0xFFFF"))); }
                            let mut data = vec![0u8; preloadLen];
                            if preloadLen > 0 { let _n = r.read(&mut data)?; }
                            let mut file = FileSource {
                                path: format!("{dir}{fileName}.{typeName}"),
                                hash,
                                data: Some(data),
                                id,
                                offset,
                                fileSize,
                                ..Default::default()
                            };
                            if file.id != 0x7FFF {
                                if !dirVpk { return Err(Error::new(ErrorKind::InvalidData, "Given VPK is not a _dir, but entry is referencing an external archive.")); }
                                file.tag = Tag::Str(format!("{blobPath}_{:03}.vpk", file.id as u16));
                            }
                            else { file.tag = Tag::Int(headerPosition.wrapping_add(treeSize) as i64); }
                            files.push(Arc::new(file));
                        }
                    }
                }
                Ok((version, treeSize, headerPosition, headerV2))
            })();
            source.setFiles(Some(files));
            let (version, treeSize, headerPosition, headerV2) = parsed?;
            if version == 2 {
                r.skip(headerV2.FileDataSectionSize as i64)?;
                let v = Verification::read(r, &headerV2)?;
                if !extended { v.verifyHashes(r, treeSize, &headerV2, headerPosition)?; }
                v.verifySignature()?;
            }
            Ok(())
        })
    }

    fn readData<'a>(&'a self, source: &'a BinaryArchive, r: Option<&'a mut dyn VfsRead>, file: &'a Arc<FileSource>, _option: &'a Tag) -> Task<'a, Option<Stream>> {
        Box::pin(async move {
            let fileDataLength = file.data.as_ref().map(|d| d.len()).unwrap_or(0);
            if file.fileSize < 0 { return Err(Error::new(ErrorKind::InvalidInput, "ArgumentOutOfRangeException: FileSize")); }
            let mut data = vec![0u8; fileDataLength + file.fileSize as usize];
            if fileDataLength > 0 { data[..fileDataLength].copy_from_slice(file.data.as_ref().unwrap()); }
            if file.fileSize == 0 { }
            else if let Tag::Int(offset) = file.tag {
                let r = r.ok_or_else(|| Error::new(ErrorKind::InvalidInput, "r"))?;
                let at = file.offset + offset;
                if at < 0 { return Err(Error::new(ErrorKind::InvalidInput, "ArgumentOutOfRangeException: Offset")); }
                r.seek(SeekFrom::Start(at as u64))?;
                let _n = r.read(&mut data[fileDataLength..])?;
            }
            else if let Tag::Str(blobPath) = &file.tag {
                let mut r2 = source.getReader(Some(blobPath))?.ok_or_else(|| Error::new(ErrorKind::InvalidData, "NullReferenceException: Reader"))?;
                if file.offset < 0 { return Err(Error::new(ErrorKind::InvalidInput, "ArgumentOutOfRangeException: Offset")); }
                r2.seek(SeekFrom::Start(file.offset as u64))?;
                let _n = r2.read(&mut data[fileDataLength..])?;
            }
            let actual = crc32_digest::compute(&data);
            if file.hash != actual as u64 {
                return Err(Error::new(ErrorKind::InvalidData, format!("CRC32 mismatch for read data (expected {:02X}, got {actual:02X})", file.hash)));
            }
            Ok(Some(Box::new(Cursor::new(data)) as Stream))
        })
    }
}

